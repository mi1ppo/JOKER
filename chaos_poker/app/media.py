"""Photo upload processing and temporary storage (sections 9.2 and 16).

Photos are re-encoded to JPEG with the long side at most 1024 px; EXIF (geotags) is dropped.
Files live in media_tmp/<room_id>/ and are deleted when the room closes or after 24 hours,
except the ones saved to the album.
"""
from __future__ import annotations

import io
import shutil
import time
from pathlib import Path

from PIL import Image, ImageOps, UnidentifiedImageError

MEDIA_ROOT = Path(__file__).resolve().parents[1] / "media_tmp"
ALLOWED_CONTENT_TYPES = {"image/jpeg", "image/png", "image/webp"}
ALLOWED_FORMATS = {"JPEG", "PNG", "WEBP", "MPO"}  # MPO: JPEG from some phone cameras
MAX_UPLOAD_BYTES = 8 * 1024 * 1024
LONG_SIDE = 1024
MAX_PIXELS = 50_000_000  # refuse decompression bombs
MAX_AGE_SEC = 24 * 3600


class PhotoRejected(ValueError):
    """The upload is not an acceptable image (message is safe to show)."""


def process_image(data: bytes) -> bytes:
    """Validate an uploaded image and return a clean JPEG without metadata."""
    if len(data) > MAX_UPLOAD_BYTES:
        raise PhotoRejected("Photo is larger than 8 MB")
    try:
        with Image.open(io.BytesIO(data)) as probe:
            if probe.format not in ALLOWED_FORMATS:
                raise PhotoRejected("Only JPEG, PNG and WebP photos are accepted")
            if probe.width * probe.height > MAX_PIXELS:
                raise PhotoRejected("Photo resolution is too large")
            probe.verify()
        with Image.open(io.BytesIO(data)) as image:
            # Apply the camera orientation before the EXIF block is dropped.
            image = ImageOps.exif_transpose(image)
            image = image.convert("RGB")
            image.thumbnail((LONG_SIDE, LONG_SIDE))
            output = io.BytesIO()
            # A fresh image saved without exif=... carries no metadata.
            image.save(output, format="JPEG", quality=85, optimize=True)
            return output.getvalue()
    except PhotoRejected:
        raise
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError) as error:
        raise PhotoRejected("The file is not a valid image") from error


class MediaStore:
    def __init__(self, root: Path = MEDIA_ROOT) -> None:
        self.root = root

    def _room_dir(self, room_id: str) -> Path:
        # Room ids are generated by the server, but keep the path inside the root anyway.
        safe = "".join(char for char in room_id if char.isalnum() or char in "_-")
        return self.root / safe

    def path(self, room_id: str, photo_id: str) -> Path:
        safe = "".join(char for char in photo_id if char.isalnum() or char in "_-")
        return self._room_dir(room_id) / f"{safe}.jpg"

    def save(self, room_id: str, photo_id: str, jpeg: bytes) -> Path:
        path = self.path(room_id, photo_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(jpeg)
        return path

    def read(self, room_id: str, photo_id: str) -> bytes:
        return self.path(room_id, photo_id).read_bytes()

    def delete(self, room_id: str, photo_id: str) -> None:
        self.path(room_id, photo_id).unlink(missing_ok=True)

    def delete_room(self, room_id: str, keep: set[str] | None = None) -> None:
        """Remove a closed room's photos, except the ones saved to the album."""
        directory = self._room_dir(room_id)
        if not directory.exists():
            return
        keep = keep or set()
        if not keep:
            shutil.rmtree(directory, ignore_errors=True)
            return
        for file in directory.glob("*.jpg"):
            if file.stem not in keep:
                file.unlink(missing_ok=True)

    def purge_older_than(self, max_age_sec: float = MAX_AGE_SEC, keep: set[str] | None = None) -> int:
        """Delete photos older than the limit (album photos in `keep` stay); returns how many."""
        if not self.root.exists():
            return 0
        keep = keep or set()
        cutoff = time.time() - max_age_sec
        removed = 0
        for file in self.root.glob("*/*.jpg"):
            if file.stem not in keep and file.stat().st_mtime < cutoff:
                file.unlink(missing_ok=True)
                removed += 1
        for directory in self.root.iterdir():
            if directory.is_dir() and not any(directory.iterdir()):
                directory.rmdir()
        return removed
